let lang = localStorage.getItem("slang") || "fr";

function applyLanguage(){
  const dict = translations[lang];
  document.documentElement.lang = lang;
  document.documentElement.dataset.lang = lang;

  document.querySelectorAll("[data-t]").forEach(el => {
    const key = el.dataset.t;
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-alt]").forEach(el => {
    const key = el.dataset.alt;
    if (dict[key] !== undefined) el.alt = dict[key];
  });

  document.title = dict.pageTitle;
  const meta = document.getElementById("metaDescription");
  if (meta) meta.setAttribute("content", dict.metaDescription);

  const subject = document.getElementById("formSubject");
  if (subject) subject.value = dict.formSubject;

  document.getElementById("lang").textContent = lang === "fr" ? "EN" : "FR";
}

document.getElementById("lang").addEventListener("click", () => {
  lang = lang === "fr" ? "en" : "fr";
  localStorage.setItem("slang", lang);
  applyLanguage();
});

applyLanguage();
document.getElementById("year").textContent = new Date().getFullYear();

